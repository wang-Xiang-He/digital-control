% =========================================================================
% Octave/MATLAB for 迴圈進階用法與 Python 差異對照
% 建議使用「在作用中的終端機中執行選取的文字」逐段測試
% =========================================================================

disp('========================================');
disp('1. 自訂步進值 (Step Size) 與倒數');
disp('========================================');
% 格式：起始值 : 步長 : 結束值 (左右皆包含)

% 每次增加 2
disp('每次增加 2 (1 到 10)：');
for i = 1:2:10
    fprintf('%d ', i);
end
fprintf('\n\n'); % 換行

% 倒數遞減
disp('倒數遞減 (5 到 1)：');
for i = 5:-1:1
    fprintf('%d ', i);
end
fprintf('\n\n');

% 🐍 Python 差異：
% 等同於 range(1, 11, 2) 與 range(5, 0, -1)。
% Octave 語法更直覺，且結束值是「包含」在內的。


disp('========================================');
disp('2. 直接迭代一維陣列');
disp('========================================');
my_array = [10.5, 20.2, 30.8];

for val = my_array
    fprintf('目前的值是: %.1f\n', val);
end
fprintf('\n');

% 🐍 Python 差異：
% 完全等同於 `for val in my_array:`，是處理一串資料時最簡潔的寫法。


disp('========================================');
disp('3. 迭代二維矩陣 (一次抓一整直行 Column)');
disp('========================================');
% 建立一個 2x3 的矩陣
A = [1, 2, 3; 
     4, 5, 6];

% 迴圈會執行 3 次，每次 col 會是 A 的一個 2x1 直行向量
for col = A
    disp('目前的行向量 (Column) 為：');
    disp(col); 
end

% 🐍 Python 差異 (極重要！)：
% 在 Python 迭代 2D Numpy Array，是一次抓一條「橫列 (Row)」出來。
% 在 Octave 中，因為底層是 Column-major (行優先)，預設是一次抓一整條「直行 (Column)」。
% 如果你想抓橫列，必須把矩陣轉置： for row = A'


disp('========================================');
disp('4. 迭代異質陣列 (Cell Array)');
disp('========================================');
mixed_data = {'Apple', 42, [1, 2; 3, 4]};

for item = mixed_data
    disp('目前處理的內容：');
    % 注意：取值必須用大括號 item{1}，不能只用 item
    disp(item{1}); 
end

% 🐍 Python 差異：
% 在 Python 中 item 會直接是該物件。
% 在 Octave 中，迴圈抓出來的 item 會被包裝在一個 1x1 的 Cell 裡。
% 所以必須用大括號 {1} 才能把真實的資料「解包」拿出來用。


disp('========================================');
disp('5. 單行寫法 (One-liner)');
disp('========================================');
% 適合在終端機互動模式快速測試，以逗號隔開
disp('印出 1 到 5 的平方：');
for i = 1:5, fprintf('%d ', i^2), end
fprintf('\n\n');

disp('--- 測試結束 ---');