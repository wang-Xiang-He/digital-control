A_ccf, B_ccf, C_ccf

%% ========================================================================
%% 2.10 相似轉換與對角化（例 2.23, 2.25）
%% ========================================================================
A = [0.8 1; 0 0.9];
B = [0; 1];
C = [1 0];

P = [1 -1; 1 1];
Aw = inv(P)*A*P;
Bw = inv(P)*B;
Cw = C*P;

disp('=== 例 2.23：任意相似轉換 ===');
Aw, Bw, Cw
disp('驗證特徵值不變：');
eig(A)
eig(Aw)

% 例 2.25：用 eig() 做對角化
[M, LAMBDA] = eig(A);
disp('=== 例 2.25：特徵向量矩陣 M 與特徵值對角矩陣 LAMBDA ===');
M, LAMBDA
disp('驗證 A*M - M*LAMBDA 應接近零矩陣：');
A*M - M*LAMBDA

%% ========================================================================
