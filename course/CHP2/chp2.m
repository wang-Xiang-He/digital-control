%% ========================================================================
%% 2.3 z 轉換的定義（例 2.2, 2.3）
%% ========================================================================
syms k a T z

Ez_step = ztrans(1^k)                       % 例 2.2：e(k)=1 -> z/(z-1)
Ez_exp  = ztrans(exp(-a*k*T))                % 例 2.3：e(k)=a^(kT) 形式 -> z/(z-exp(-a*T))

%% ========================================================================
%% 2.4 z 轉換的性質（例 2.6：複數平移定理）
%% ========================================================================
ekT = (k*T)*exp(a*k*T);
Ez_complex_shift = ztrans(ekT)               % (T*z*exp(T*a))/(z - exp(T*a))^2

%% ========================================================================
%% 2.5 由 s 域求 z 轉換（例 2.9）
%% ========================================================================
T = 0.1;
num = [1 4 3];
denom = [1 6 8 0];              % s(s+2)(s+4)，不可有重根
n = length(denom);
Es = tf(num, denom)             % 先看一下 s 域轉移函數

[r, p, kdir] = residue(num, denom);   % 部分分式：留數 r、極點 p、直接項 kdir
pz = zeros(1, n-1);
for i = 1:n-1
    pz(i) = exp(p(i)*T);        % s 域極點 p -> z 域極點 exp(p*T)
end

[numzz, denomz] = residue(r, pz, kdir);  % 用留數/極點合併回多項式
numz = conv(numzz, [1 0]);               % 乘上一個 z
Ez_from_s = tf(numz, denomz, T)          % 應為 (z^3-1.658z^2+0.6804z)/(z^3-2.489z^2+2.038z-0.5488)

% 另一種做法：先反拉普拉斯回到時域，代入 t=kT，再取 z 轉換
syms s t
Es_sym = (s^2+4*s+3)/(s^3+6*s^2+8*s);
et = ilaplace(Es_sym);
ekT2 = subs(et, t, k*T);
Ez_alt = ztrans(ekT2);
pretty(Ez_alt)

%% ========================================================================
%% 2.6 差分方程式的解法（例 2.10：逐次代入法）
%% ========================================================================
mkminus1 = 0;   % m(-1)
ekminus1 = 0;   % e(-1)
ek = 1;         % e(0)
disp('=== 例 2.10：逐次代入法求 m(k) ===');
for kk = 0:6
    mk = ek - ekminus1 - mkminus1;
    fprintf('k=%d, m(k)=%d\n', kk, mk);
    mkminus1 = mk;
    ekminus1 = ek;
    ek = 1 - ek;
end

%% ========================================================================
%% 2.7 反 z 轉換（例 2.13, 2.16：partial fraction / 重根）
%% ========================================================================
syms kk_sym
Ez1 = z/((z-1)*(z-2));
disp('=== 例 2.13：反 z 轉換 z/((z-1)(z-2)) ===');
iztrans(Ez1, kk_sym)            % 應為 2^k - 1

Ez2 = z/(z-1)^2;
disp('=== 例 2.16：反 z 轉換 z/(z-1)^2（重根） ===');
iztrans(Ez2, kk_sym)            % 應為 k

% 例 2.14：共軛複數極點 -> 用 residue 找留數與極點，再轉成正弦形式
num14 = [0, 0, -3.894];
den14 = [1, 0, 0.6065];
[r14, p14, k14] = residue(num14, den14);
disp('=== 例 2.14：共軛複數極點的留數與極點 ===');
disp('r ='); disp(r14);
disp('p ='); disp(p14);

% 例 2.17：離散摺積求反 z 轉換
e1 = [1 1 1 1 1 1];
e2 = [0 1 2 4 8 16];
e_conv = conv(e1, e2);
disp('=== 例 2.17：離散摺積 e1(k)*e2(k) ===');
disp(e_conv);

%% ========================================================================
%% 2.9 狀態變數：控制標準型 (CCF)（例 2.19）
%% ========================================================================
% G(z) = (z^2+2z+1) / (z^3+2z^2+z+0.5)
b = [1 2 1];      % b0 b1 b2
a0 = 0.5; a1 = 1; a2 = 2;

A_ccf = [0 1 0; 0 0 1; -a0 -a1 -a2];
