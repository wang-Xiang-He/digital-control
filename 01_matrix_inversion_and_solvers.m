% Python 中沒有反斜線運算子，必須呼叫專用函數：
% x_direct = np.linalg.solve(A, b)   # 推薦做法 (等同 Octave 的 A \ b)
% x_slow   = np.linalg.inv(A) @ b    # 較慢且誤差易放大