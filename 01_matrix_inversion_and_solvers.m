% =========================================================================
% 模組一：反矩陣、虛擬反矩陣與線性系統求解 (Ax = b)
% =========================================================================

% 建立一個 3x3 狀態矩陣 A 與 3x1 輸入向量 b
A = [1,  2, -1;
     2,  1,  0;
    -1,  1,  2];

b = [1; 2; 3]; % 3x1 column 向量

% -------------------------------------------------------------------------
% 1. 行列式值 (Determinant) 與 矩陣秩 (Rank)
% -------------------------------------------------------------------------
det_A = det(A);
rank_A = rank(A);
% python np.linalg.det(A)
% python np.linalg.matrix_rank(A)
fprintf('det(A) = %.4f, rank(A) = %d\n', det_A, rank_A);

% 🐍 Python 對照：
% det_A  = np.linalg.det(A)
% rank_A = np.linalg.matrix_rank(A)


% -------------------------------------------------------------------------
% 2. 反矩陣 (Matrix Inverse)
% -------------------------------------------------------------------------
% 用於求解非奇異方陣的逆矩陣
A_inv = inv(A);
disp('A 的反矩陣 (inv):');
disp(A_inv);

% 驗證 A * A_inv = I (3x3 單位矩陣)
disp('驗證 A * inv(A):');
disp(round(A * A_inv)); 

% 🐍 Python 對照：
% A_inv = np.linalg.inv(A)
% 驗證： np.round(A @ A_inv)


% -------------------------------------------------------------------------
% 3. 虛擬反矩陣 / 廣義逆矩陣 (Moore-Penrose Pseudoinverse)
% -------------------------------------------------------------------------
% 當矩陣非方陣 (例如感測器數量與狀態數不同) 或不可逆時，用於最小平方求解
C = [1, 2, 3; 
     4, 5, 6]; % 2 個 row, 3 個 column 的長方矩陣

C_pinv = pinv(C);
disp('C 的虛擬反矩陣 (pinv):');
disp(C_pinv);

% 🐍 Python 對照：
% C_pinv = np.linalg.pinv(C)


% -------------------------------------------------------------------------
% 4. 線性方程組求解 Ax = b (極度重要：避免手動寫 inv(A)*b)
% -------------------------------------------------------------------------
% 在數值計算中，直接使用反斜線「\」(左除) 效率與穩定度遠高於 inv(A)*b
x_direct = A \ b;          % 採用高斯消去法求解
x_slow   = inv(A) * b;     % 數值上較不推薦

disp('求解 Ax = b 的解向量 x:');
disp('direct')
disp(x_direct);
disp('slow')
disp(x_slow);

